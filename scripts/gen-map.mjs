// Generates a dotted world map as a single SVG path (equirectangular).
// Run: node scripts/gen-map.mjs  -> src/components/illustrations/worldDots.ts
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { geoContains } from 'd3-geo'
import { feature } from 'topojson-client'

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/land-50m.json', import.meta.url)))
const land = feature(topo, topo.objects.land)

const K = 5, LAT_TOP = 80, LAT_BOTTOM = -58, STEP = 2
let d = ''
for (let lat = LAT_TOP - STEP / 2; lat > LAT_BOTTOM; lat -= STEP) {
  for (let lon = -180 + STEP / 2; lon < 180; lon += STEP) {
    if (geoContains(land, [lon, lat])) {
      const x = Math.round((lon + 180) * K)
      const y = Math.round((LAT_TOP - lat) * K)
      d += `M${x} ${y}h0`
    }
  }
}
const W = 360 * K, H = (LAT_TOP - LAT_BOTTOM) * K
mkdirSync(new URL('../src/components/illustrations/', import.meta.url), { recursive: true })
writeFileSync(new URL('../src/components/illustrations/worldDots.ts', import.meta.url),
`// Generated by scripts/gen-map.mjs from Natural Earth (world-atlas). Do not edit.
export const MAP_W = ${W}
export const MAP_H = ${H}
export const MAP_K = ${K}
export const MAP_LAT_TOP = ${LAT_TOP}
export const WORLD_DOTS = '${d}'
`)
console.log('dots', d.split('M').length - 1, 'bytes', d.length)
